package publisher

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"os/exec"
	"strings"

	"github.com/geevheit/neuralcenter/api/internal/app"
)

var (
	ErrGitInitFailed   = errors.New("falha ao inicializar repositório git no workspace")
	ErrGitCommitFailed = errors.New("falha ao criar commit inicial no workspace")
)

// LocalPublisher cria versionamento git local e prepara o pacote para prévia
type LocalPublisher struct {
	apiBaseURL string
	sandbox    app.SandboxManager
}

func NewLocalPublisher(apiBaseURL string, sandbox app.SandboxManager) *LocalPublisher {
	if apiBaseURL == "" {
		apiBaseURL = "http://localhost:8080"
	}
	return &LocalPublisher{
		apiBaseURL: strings.TrimRight(apiBaseURL, "/"),
		sandbox:    sandbox,
	}
}

// PublishWorkspace executa versionamento atômico git e define a URL de prévia
func (p *LocalPublisher) PublishWorkspace(ctx context.Context, cardID string, commitMsg string) (*app.PublishedPreviewDTO, error) {
	wsPath := p.sandbox.GetWorkspacePath(cardID)
	if wsPath == "" {
		return nil, fmt.Errorf("caminho de workspace inválido para cartão %s", cardID)
	}

	if commitMsg == "" {
		commitMsg = fmt.Sprintf("feat(%s): autonomous build generated by GeevheitNeural", cardID)
	}

	// 1. Inicializar git local (se ainda não existir)
	initCmd := exec.CommandContext(ctx, "git", "init")
	initCmd.Dir = wsPath
	if err := initCmd.Run(); err != nil {
		return nil, fmt.Errorf("%w: %v", ErrGitInitFailed, err)
	}

	// 2. Configurar autor do commit localmente
	_ = exec.CommandContext(ctx, "git", "-C", wsPath, "config", "user.name", "GeevheitNeural Bot").Run()
	_ = exec.CommandContext(ctx, "git", "-C", wsPath, "config", "user.email", "bot@geevheit.internal").Run()

	// 3. Adicionar todos os arquivos
	addCmd := exec.CommandContext(ctx, "git", "add", ".")
	addCmd.Dir = wsPath
	_ = addCmd.Run()

	// 4. Criar commit
	commitCmd := exec.CommandContext(ctx, "git", "commit", "-m", commitMsg, "--allow-empty")
	commitCmd.Dir = wsPath
	if err := commitCmd.Run(); err != nil {
		return nil, fmt.Errorf("%w: %v", ErrGitCommitFailed, err)
	}

	// 5. Capturar hash do commit
	var outBuf bytes.Buffer
	revCmd := exec.CommandContext(ctx, "git", "rev-parse", "HEAD")
	revCmd.Dir = wsPath
	revCmd.Stdout = &outBuf
	_ = revCmd.Run()

	commitHash := strings.TrimSpace(outBuf.String())
	if len(commitHash) > 12 {
		commitHash = commitHash[:12]
	}

	// 6. Gerar URL de prévia na API Geevheit
	previewURL := fmt.Sprintf("%s/v1/cards/%s/preview", p.apiBaseURL, cardID)

	return &app.PublishedPreviewDTO{
		CommitHash: commitHash,
		PreviewURL: previewURL,
		Branch:     "main",
		Message:    fmt.Sprintf("Build publicado com sucesso no hash %s", commitHash),
	}, nil
}

